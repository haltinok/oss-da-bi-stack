"""Write postgres/init/10_rls_dimensions.sql (the default row-level dimensions a new access database is seeded with) from cube/rls_dimensions.json.

  python3 scripts/rls_dimensions_sql.py            # rewrite the file
  python3 scripts/rls_dimensions_sql.py --check    # exit 1 if it is out of date (dashboards/tests/test_rls_dimensions.py does the same)

The seed only inserts ids that are missing, so it never overwrites a dimension changed in the database (PLAN-rls-registry-db.md).
"""
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
SOURCE = REPO / "cube" / "rls_dimensions.json"
TARGET = REPO / "postgres" / "init" / "10_rls_dimensions.sql"
sys.path.insert(0, str(REPO / "auth"))
import rls_registry  # noqa: E402  (the same validation the services use)


def lit(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def jsonb(value) -> str:
    return lit(json.dumps(value, ensure_ascii=False, sort_keys=True)) + "::jsonb"


def render(dims: list) -> str:
    dims = rls_registry.normalize(dims)
    rows = []
    for i, d in enumerate(dims):
        cubes = "ARRAY[" + ", ".join(lit(c) for c in d["cubes"]) + "]"
        rows.append(f"    ({lit(d['id'])}, {(i + 1) * 10}, {lit(d['member'])}, {cubes}, {lit(d['when_empty'])}, {jsonb(d['values'])}, "
                    f"{'true' if d['seed'] else 'false'}, {jsonb(d['labels'])}, {lit(d['empty_message'])})")
    return (
        "-- The default row-level dimensions (generated by scripts/rls_dimensions_sql.py from cube/rls_dimensions.json: edit that file and run the script,\n"
        "-- never this one). Idempotent: an id already in access.rls_dimension is left as it is, so a change made in the database is never overwritten.\n"
        "-- Cube, the auth service and the admin console read the table when they start (PLAN-rls-registry-db.md).\n"
        "INSERT INTO access.rls_dimension (id, position, member, cubes, when_empty, values_source, seed, labels, empty_message) VALUES\n"
        + ",\n".join(rows)
        + "\nON CONFLICT (id) DO NOTHING;\n"
    )


def main(argv: list[str]) -> int:
    text = render(json.loads(SOURCE.read_text(encoding="utf-8"))["dimensions"])
    if "--check" in argv:
        if TARGET.read_text(encoding="utf-8") != text:
            print(f"{TARGET.relative_to(REPO)} is out of date: run python3 scripts/rls_dimensions_sql.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
